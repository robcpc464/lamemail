Lang langFrom(const QString& locale)
{
    return locale.startsWith(QLatin1String("de")) ? Lang::De : Lang::En;
}

Lang lang()
{
    static const Lang detected = [] {
        for (const char* name : { "LC_ALL", "LC_MESSAGES", "LANG" }) {
            const QString value = qEnvironmentVariable(name);
            if (!value.isEmpty())
                return langFrom(value);
        }
        return Lang::En;
    }();
    return detected;
}

const Texts& texts(Lang lang) { return lang == Lang::De ? de : en; }

const Texts& texts() { return texts(lang()); }

QVariantList Strings::dates(const QDateTime& when) const
{
    QVariantList dates;
    for (const DateLength& length : texts().dateLengths)
        dates.append(QVariantMap {
            { QStringLiteral("name"), QString::fromUtf8(length.name) },
            { QStringLiteral("text"), dateText(when.date(), length.format, lang()) },
        });
    return dates;
}
